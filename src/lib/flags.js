export function flagUrl(id, size = 320) {
  if (!id) return "";
  const found = FLAGS.find((f) => f.id === id);
  if (found && found.src) return found.src;
  return `https://flagcdn.com/w${size}/${id}.png`;
}

export function flagLabel(id) {
  const found = FLAGS.find((f) => f.id === id);
  return found ? found.label : "";
}

