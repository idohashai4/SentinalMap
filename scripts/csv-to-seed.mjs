// Converts the Base44 CSV exports in ./data into
//   supabase/migrations/20261113000100_import_base44_data.sql — the data, as a migration
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function parseCsv(text) {
  const rows = []; let row = []; let cell = ''; let quoted = false;
  text = text.replace(/^﻿/, '');
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') { if (text[i + 1] === '"') { cell += '"'; i++; } else quoted = false; }
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (c !== '\r') cell += c;
  }
  if (cell !== '' || row.length) { row.push(cell); rows.push(row); }
  const [head, ...body] = rows;
  return body.filter(r => r.length === head.length).map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}
const load = name => parseCsv(readFileSync(join(root, 'data', name + '.csv'), 'utf8'));

// Base44 stores naive timestamps; keep the wall-clock value and mark it as UTC.
const ts = v => !v ? null : /Z$|[+-]\d\d:?\d\d$/.test(v) ? v : v + 'Z';
const num = v => (v === '' || v == null ? null : Number(v));
const base = r => ({ id: r.id, created_date: ts(r.created_date), updated_date: ts(r.updated_date) });

const tables = {
  poi_topics: load('poi_topics').map(r => ({ ...base(r), name: r.name, color: r.color, description: r.description })),
  points_of_interest: load('points_of_interest').map(r => ({
    ...base(r), title: r.title, topic: r.topic, event_date: r.event_date || null,
    latitude: num(r.latitude), longitude: num(r.longitude), description: r.description,
    marker_color: r.marker_color, media_url: r.media_url || null, tags: r.tags ? JSON.parse(r.tags) : null,
  })),
  place_labels: load('place_labels').map(r => ({
    ...base(r), name: r.name, latitude: num(r.latitude), longitude: num(r.longitude), color: r.color, font_size: r.font_size || 'medium',
  })),
  map_shapes: load('map_shapes').map(r => ({
    ...base(r), shape_type: r.shape_type, geojson: r.geojson, label: r.label, color: r.color,
    fill_type: r.fill_type || 'color', flag: r.flag || null, opacity: num(r.opacity) ?? 0.3, layer_name: r.layer_name || 'default',
  })),
  layer_notes: load('layer_notes').map(r => ({
    ...base(r), shape_id: r.shape_id || null, layer_name: r.layer_name, kind: r.kind, title: r.title, text: r.text, url: r.url,
  })),
};

const lit = v => v === null || v === undefined ? 'null'
  : typeof v === 'number' ? String(v)
  : typeof v === 'object' ? `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`
  : `'${String(v).replace(/'/g, "''")}'`;

let sql = '-- Generated by scripts/csv-to-seed.mjs from the Base44 exports. Safe to re-run: existing rows are left alone.\nbegin;\n';
for (const [name, rows] of Object.entries(tables)) {
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  sql += `\n-- ${name}: ${rows.length} rows\n`;
  for (const r of rows) sql += `insert into public.${name} (${cols.join(', ')}) values (${cols.map(c => lit(r[c])).join(', ')}) on conflict (id) do nothing;\n`;
}
// The people who created the exported records are the ones allowed to sign in.
const owners = [...new Set(['points_of_interest', 'map_shapes', 'layer_notes', 'place_labels', 'poi_topics']
  .flatMap(name => load(name).map(r => (r.created_by || '').toLowerCase()))
  .filter(e => e && !e.endsWith('@no-reply.base44.com')))];
sql += `\n-- allowed_emails: ${owners.length} rows\n`;
for (const email of owners) sql += `insert into public.allowed_emails (email) values (${lit(email)}) on conflict (email) do nothing;\n`;

sql += '\ncommit;\n';
writeFileSync(join(root, 'supabase', 'migrations', '20261113000100_import_base44_data.sql'), sql);
if (process.env.SEED_JSON) writeFileSync(process.env.SEED_JSON, JSON.stringify(tables));
for (const [n, r] of Object.entries(tables)) console.log(n.padEnd(20), r.length);
